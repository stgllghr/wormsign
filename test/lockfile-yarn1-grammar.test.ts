/*
 * yarn 1.22.22 reads a quoted key (`"resolved" "url"`) as the key, and when its own grammar fails it reads the whole
 * file as YAML, where `resolved: url` is the key. A line the reader skipped could therefore be the URL yarn installs
 * from. Quoted keys are read; every line outside the grammar yarn writes throws.
 */

const EVIL = "http://127.0.0.1:18765/evil.tgz#0123456789abcdef0123456789abcdef01234567";
const IOC_TARBALL = "https://registry.yarnpkg.com/wormsign-test-marker/-/wormsign-test-marker-1.0.0.tgz";
const HEAD = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n";
const entry = (resolvedLine: string, integrityLine = "  integrity sha512-x") => `${HEAD}foo@^1.0.0:\n  version "1.0.0"\n${resolvedLine}\n${integrityLine}\n`;
const clean = entry('  resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz#0123456789abcdef0123456789abcdef01234567"');

const parse = (text: string) => parseLockfileText("yarn.lock", text)?.packages;

test("yarn 1: a quoted key is the same field yarn reads", () => {
  assert.deepEqual(parse(entry(`  "resolved" "${EVIL}"`)), [{ name: "foo", version: "1.0.0", resolved: EVIL.replace(/#.*$/, ""), integrity: "sha512-x" }]);
  assert.equal(parse(entry(`  "resolved" "${EVIL}"`, '  "integrity" "sha512-y"'))?.[0]?.integrity, "sha512-y");
  assert.equal(parse(`${HEAD}foo@^1.0.0:\n  "version" "1.0.0"\n  resolved "${EVIL}"\n`)?.[0]?.version, "1.0.0");
  // yarn's tokenizer ends a line at a lone CR too, so the field after one is read.
  assert.equal(parse(`${HEAD}foo@^1.0.0:\n  version "1.0.0"\r  resolved "${EVIL}"\n`)?.[0]?.resolved, EVIL.replace(/#.*$/, ""));
});

test("yarn 1: lines outside the grammar yarn writes throw instead of being skipped", () => {
  const bad: [string, string][] = [
    ["colon form (yarn reads the file as YAML)", entry(`  resolved: "${EVIL}"`)],
    ["quoted colon form", entry(`  "resolved": "${EVIL}"`)],
    ["colon form of integrity", entry('  resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz"', "  integrity: sha512-x")],
    ["two fields on one line (yarn reads both)", entry(`  integrity sha512-x resolved "${EVIL}"`, "")],
    ["comma-joined keys (yarn sets both)", entry(`  uid, resolved "${EVIL}"`)],
    ["duplicate resolved (yarn keeps the last)", entry(`  resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz"\n  resolved "${EVIL}"`)],
    ["duplicate version", `${HEAD}foo@^1.0.0:\n  version "1.0.0"\n  version "2.0.0"\n`],
    ["unknown field (name renames the package in yarn)", entry('  name "evil"')],
    ["an indented comment", entry("  # hidden")],
    ["a 4-space line outside dependencies", `${HEAD}foo@^1.0.0:\n  version "1.0.0"\n    resolved "${EVIL}"\n`],
    ["a tab-indented field", `${HEAD}foo@^1.0.0:\n  version "1.0.0"\n\tresolved "${EVIL}"\n`],
    ["a header yarn cannot tokenize", `${HEAD}@scope/foo@^1.0.0:\n  version "1.0.0"\n`],
    ["a whole-YAML lockfile", `${HEAD}foo@^1.0.0:\n  version: 1.0.0\n  resolved: ${EVIL}\n`],
  ];
  for (const [why, text] of bad) assert.throws(() => parse(text), /yarn\.lock line \d+/, why);
});

test("yarn 1: every lockfile yarn 1.22.22 wrote in the fixtures still parses", () => {
  for (const d of ["yarn1", "protocols/yarn1", "protocols/empty-yarn1"]) {
    const text = readFileSync(fx("lockfiles", d, "yarn.lock"), "utf8");
    assert.doesNotThrow(() => parse(text), d);
    assert.doesNotThrow(() => parse(text.replace(/\n/g, "\r\n")), `${d} (CRLF)`);
  }
});

function dir(files: Record<string, string>): string {
  const d = mkdtempSync(join(tmpdir(), "ws-y1-"));
  for (const [p, text] of Object.entries(files)) {
    mkdirSync(dirname(join(d, p)), { recursive: true });
    writeFileSync(join(d, p), text);
  }
  return d;
}
const mem = (files: Record<string, string>, label = "mem"): Tree => ({ label, list: () => Object.keys(files), read: (p) => files[p] });
const PKG = JSON.stringify({ name: "app", private: true, dependencies: { foo: "^1.0.0" } });

async function scan(lock: string) {
  const io = fakeIO();
  const code = await run(["scan", dir({ "package.json": PKG, "yarn.lock": lock }), "--format", "json", "--iocs", fx("iocs")], io);
  return { code, ids: (JSON.parse(io.out) as { findings: { ruleId: string; severity: string }[] }).findings.map((f) => `${f.ruleId}:${f.severity}`) };
}

test("scan: a quoted resolved key is checked like an unquoted one; a colon form fails closed", async () => {
  assert.deepEqual((await scan(entry(`  "resolved" "${EVIL}"`))).ids, ["WS-LK-002:high"]);
  assert.deepEqual((await scan(entry(`  "resolved" "${IOC_TARBALL}"`))).ids.sort(), ["WS-LK-001:critical", "WS-LK-002:high"]);
  const colon = await scan(entry(`  resolved: "${EVIL}"`));
  assert.deepEqual(colon.ids, ["WS-SC-900:high"]);
  assert.equal(colon.code, 1);
});

test("diff: a quoted resolved key added by a change is checked; a colon form is unreadable", () => {
  const ids = (head: string) => diffTrees(mem({ "yarn.lock": clean }), mem({ "yarn.lock": head }), testCtx()).findings.map((f) => `${f.ruleId}:${f.severity}`).sort();
  assert.deepEqual(ids(entry(`  "resolved" "${EVIL}"`)), ["WS-LK-002:high"]);
  assert.deepEqual(ids(entry(`  "resolved" "${IOC_TARBALL}"`)), ["WS-LK-001:critical", "WS-LK-002:high"]);
  assert.deepEqual(ids(entry(`  resolved: "${EVIL}"`)), ["WS-DF-006:high"]);
  assert.deepEqual(ids(entry('  resolved "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz"', '  "integrity": "sha512-x"')), ["WS-DF-006:high"]);
});

test("soak: a quoted resolved key is the artifact checked; a colon form fails closed", async () => {
  // The registry has foo@1.0.0, old and with integrity sha512-x: only the tarball's source differs.
  const fetchImpl = (async (url: string | URL) => {
    if (String(url) === "https://api.osv.dev/v1/querybatch") return new Response(JSON.stringify({ results: [{}] }));
    const time = { "1.0.0": new Date(NOW.getTime() - 9000 * 3_600_000).toISOString() };
    return new Response(JSON.stringify({ name: "foo", time, versions: { "1.0.0": { dist: { integrity: "sha512-x", tarball: "https://registry.npmjs.org/foo/-/foo-1.0.0.tgz" } } } }));
  }) as typeof fetch;
  const soak = async (lock: string) => {
    const io = fakeIO({ fetchImpl, env: { HOME: mkdtempSync(join(tmpdir(), "ws-home-")) } });
    const code = await run(["soak", dir({ "package.json": PKG, "yarn.lock": lock }), "--format", "json"], io);
    return { code, high: (JSON.parse(io.out) as { findings: { ruleId: string; severity: string }[] }).findings.filter((f) => f.severity === "high").map((f) => f.ruleId) };
  };
  assert.deepEqual((await soak(clean)).high, [], "control: the clean entry passes");
  for (const lock of [entry(`  "resolved" "${EVIL}"`), entry(`  resolved: "${EVIL}"`), entry(`  "resolved" "${EVIL}"`, '  "integrity" "sha512-x"')]) {
    const r = await soak(lock);
    assert.deepEqual(r.high, ["WS-SK-002"], lock);
    assert.equal(r.code, 1);
  }
});

/*
 * yarn 1 checks a tarball against the SHA-1 in its resolved URL's fragment (yarn 1.22.22: PackageRequest.getLocked
 * passes it on as the remote's hash, TarballFetcher._findIntegrity falls back to ssri.fromHex(hash, 'sha1')), so an
 * entry yarn wrote before it added integrity lines is not unverified. Old lockfiles are mostly such entries: react's
 * 19 Yarn 1 lockfiles gave 5,670 false WS-LK-003 findings (docs/evidence/false-positives.md).
 */
const SHA1_HEX = "0123456789abcdef0123456789abcdef01234567";
const SHA1 = `sha1-${Buffer.from(SHA1_HEX, "hex").toString("base64")}`;
const REGISTRY_URL = "https://registry.yarnpkg.com/foo/-/foo-1.0.0.tgz";
const noIntegrity = (resolved: string) => `${HEAD}foo@^1.0.0:\n  version "1.0.0"\n  resolved "${resolved}"\n`;

test("yarn 1: the resolved URL's sha1 fragment is the integrity when there is no integrity line", () => {
  assert.deepEqual(parse(noIntegrity(`${REGISTRY_URL}#${SHA1_HEX}`)), [{ name: "foo", version: "1.0.0", resolved: REGISTRY_URL, integrity: SHA1 }]);
  // An integrity line wins wherever it stands; yarn checks both.
  assert.equal(parse(entry(`  resolved "${REGISTRY_URL}#${SHA1_HEX}"`, "  integrity sha512-x"))?.[0]?.integrity, "sha512-x");
  assert.equal(parse(`${HEAD}foo@^1.0.0:\n  version "1.0.0"\n  integrity sha512-x\n  resolved "${REGISTRY_URL}#${SHA1_HEX}"\n`)?.[0]?.integrity, "sha512-x");
  // A git source's fragment is the commit; anything but 40 lower-case hex digits is not a hash yarn wrote.
  for (const resolved of [`git+https://github.com/a/foo.git#${SHA1_HEX}`, `git://github.com/a/foo#${SHA1_HEX}`, `git+ssh://git@github.com/a/foo.git#${SHA1_HEX}`, `https://github.com/a/foo.git#${SHA1_HEX}`, `${REGISTRY_URL}#${SHA1_HEX.slice(1)}`, `${REGISTRY_URL}#${SHA1_HEX.toUpperCase()}`, REGISTRY_URL]) {
    assert.equal(parse(noIntegrity(resolved))?.[0]?.integrity, undefined, resolved);
  }
});

test("scan: a yarn 1 entry with a sha1 fragment and no integrity line is not reported as missing integrity", async () => {
  assert.deepEqual((await scan(noIntegrity(`${REGISTRY_URL}#${SHA1_HEX}`))).ids, []);
  assert.deepEqual((await scan(noIntegrity(REGISTRY_URL))).ids, ["WS-LK-003:medium"], "control: no fragment, no integrity");
  assert.deepEqual((await scan(noIntegrity(`${REGISTRY_URL}#${SHA1_HEX.slice(1)}`))).ids, ["WS-LK-003:medium"], "not a sha1");
});

test("soak: a yarn 1 sha1 fragment is compared with the registry's shasum", async () => {
  // The registry's foo@1.0.0 is old, with shasum SHA1_HEX and no sha512 the lockfile could carry.
  const fetchImpl = (async (url: string | URL) => {
    if (String(url) === "https://api.osv.dev/v1/querybatch") return new Response(JSON.stringify({ results: [{}] }));
    const time = { "1.0.0": new Date(NOW.getTime() - 9000 * 3_600_000).toISOString() };
    return new Response(JSON.stringify({ name: "foo", time, versions: { "1.0.0": { dist: { shasum: SHA1_HEX, tarball: "https://registry.npmjs.org/foo/-/foo-1.0.0.tgz" } } } }));
  }) as typeof fetch;
  const soak = async (lock: string) => {
    const io = fakeIO({ fetchImpl, env: { HOME: mkdtempSync(join(tmpdir(), "ws-home-")) } });
    await run(["soak", dir({ "package.json": PKG, "yarn.lock": lock }), "--format", "json"], io);
    return (JSON.parse(io.out) as { findings: { ruleId: string; severity: string; message: string }[] }).findings.filter((f) => f.severity === "high");
  };
  assert.deepEqual(await soak(noIntegrity(`${REGISTRY_URL}#${SHA1_HEX}`)), [], "control: the registry's own tarball and hash");
  // The registry's URL, but another tarball's hash: yarn 1 would install only that other tarball.
  const other = await soak(noIntegrity(`${REGISTRY_URL}#${"f".repeat(40)}`));
  assert.deepEqual(other.map((f) => f.ruleId), ["WS-SK-002"]);
  assert.match(other[0]?.message ?? "", /integrity differs/);
  // Another URL on the registry host, with the registry's hash: the content is proven whatever the URL says.
  assert.deepEqual(await soak(noIntegrity(`https://registry.yarnpkg.com/foo/-/renamed.tgz#${SHA1_HEX}`)), []);
});
